def pitch_of(tok):
    octv = 0
    if '^' in tok:
        octv = 1; tok = tok.replace('^', '')
    if '_' in tok:
        octv = -1; tok = tok.replace('_', '')
    acc = 0
    if tok[:1] == '#':
        acc = 1; tok = tok[1:]
    elif tok[:1] == 'b':
        acc = -1; tok = tok[1:]
    d = int(tok)
    if d == 0:
        return None
    return BASE + DEG[d] + 12 * octv + acc


bars = []
for page in (P1, P2, P3):
    for seg in page.split('|'):
        items = seg.split()
        if items:
            bars.append(items)

t = 0.0
notes = []
bad = []
for bi, items in enumerate(bars):
    tot = 0.0
    tt = t
    for it in items:
        name, val = it.split(':')
        du = float(val)
        p = pitch_of(name)
        if p is not None:
            notes.append((tt, du, p))
        tt += du
        tot += du
    if abs(tot - 6) > 1e-9:
        bad.append((bi + 1, round(tot, 3), ' '.join(items)))
    t += 6

print('bars', len(bars), 'notes', len(notes), 'bad', len(bad))
for b in bad:
    print('  BAD', b)


def vlq(v):
    b = [v & 0x7f]; v >>= 7
    while v:
        b.append((v & 0x7f) | 0x80); v >>= 7
    return bytes(reversed(b))


ev = [
    (0, bytes([0xFF, 0x51, 0x03]) + struct.pack('>I', TEMPO)[1:]),
    (0, bytes([0xFF, 0x03]) + vlq(5) + b'VOCAL'),
    (0, bytes([0xC0, 48])),
]
for tick, du, p in notes:
    on = int(round(tick * EIGHTH))
    off = int(round((tick + du) * EIGHTH))
    off = max(off, on + 20)
    ev.append((on, bytes([0x90, p, 100])))
    ev.append((off, bytes([0x80, p, 0])))

ev.sort(key=lambda e: (e[0], e[1]))
out = bytearray(); last = 0
for tk, d in ev:
    out += vlq(tk - last) + d; last = tk
out += vlq(0) + b'\xff\x2f\x00'
mid = b'MThd' + struct.pack('>IHHH', 6, 0, 1, PPQ) + \
      b'MTrk' + struct.pack('>I', len(out)) + bytes(out)
io.open('/tmp/voc6.mid', 'wb').write(mid)
io.open('/tmp/voc6.b64', 'w').write(base64.b64encode(mid).decode())
secs = t / 2.0 * (TEMPO / 1e6)
print('bytes', len(mid), 'len', int(secs // 60), 'm', round(secs % 60, 1), 's',
      'pitch', min(n[2] for n in notes), max(n[2] for n in notes))